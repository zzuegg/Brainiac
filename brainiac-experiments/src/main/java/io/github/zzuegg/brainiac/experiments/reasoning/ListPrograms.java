package io.github.zzuegg.brainiac.experiments.reasoning;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.SplittableRandom;

/**
 * A toy list-processing DSL shared by the program-synthesis experiments (skill libraries,
 * library learning, self-modifying coders). It extends the digit DSL of
 * {@link AbsoluteZero}: the arithmetic primitives {@code +d} and {@code *d} map
 * {@link AbsoluteZero#execute} over every element, and structural primitives reorder,
 * filter and copy the list. A program is a sequence of primitive names run left to right.
 * Unlike the one-digit DSL, whose 100 affine functions are all reachable in two steps,
 * the list primitives do not collapse, so longer programs really do compute new things.
 *
 * <p>Tasks are input/output examples generated by a hidden program built from named
 * <em>concepts</em> (short primitive sequences such as {@code sort rev}), so a task named
 * {@code "descending evens"} is solved by gluing the solutions of {@code "descending"} and
 * {@code "evens"}; this is the structure that skill libraries and learned abstractions
 * exploit.
 */
public final class ListPrograms {

    /** The structural primitives. */
    private static final List<String> STRUCTURAL = List.of("rev", "sort", "uniq", "tail", "init", "even", "odd",
            "dbl", "head2", "swap");

    private static final List<String> PRIMITIVES;

    static {
        List<String> p = new ArrayList<>(STRUCTURAL);
        for (int d = 1; d <= 5; d++) {
            p.add("+" + d);
        }
        for (int d : new int[] {2, 3, 5, 7}) {
            p.add("*" + d);
        }
        PRIMITIVES = List.copyOf(p);
    }

    /**
     * A named concept: a short program the tasks are built from.
     *
     * @param name the concept's name, one word
     * @param program its primitives
     */
    public record Concept(String name, List<String> program) {
    }

    /**
     * Named concepts of two primitives each, chosen so that gluing them rarely collapses into
     * something shorter (only two are arithmetic, whose compositions are affine maps).
     */
    public static final List<Concept> CONCEPTS = List.of(
            new Concept("descending", List.of("sort", "rev")),
            new Concept("evens", List.of("even", "uniq")),
            new Concept("shifted", List.of("+3", "*3")),
            new Concept("trimmed", List.of("tail", "init")),
            new Concept("mirrored", List.of("dbl", "rev")),
            new Concept("scaled", List.of("*7", "+1")),
            new Concept("ascending", List.of("uniq", "sort")),
            new Concept("swapped", List.of("swap", "tail")),
            new Concept("bumped", List.of("+5", "swap")),
            new Concept("folded", List.of("rev", "+2")));

    /**
     * A synthesis task.
     *
     * @param name its description: the names of the concepts the hidden program glues
     * @param inputs the example inputs
     * @param outputs the expected outputs
     * @param hidden the program that generated the outputs (never shown to a solver)
     * @param level how many concepts it glues
     */
    public record Task(String name, int[][] inputs, int[][] outputs, List<String> hidden, int level) {
        /**
         * @param program a candidate
         * @return whether it reproduces every example
         */
        public boolean solvedBy(List<String> program) {
            for (int i = 0; i < inputs.length; i++) {
                int[] out = execute(program, inputs[i]);
                if (out == null || !Arrays.equals(out, outputs[i])) {
                    return false;
                }
            }
            return true;
        }

        /**
         * @param program a candidate
         * @return how many examples it gets right
         */
        public int examplesRight(List<String> program) {
            int right = 0;
            for (int i = 0; i < inputs.length; i++) {
                int[] out = execute(program, inputs[i]);
                right += out != null && Arrays.equals(out, outputs[i]) ? 1 : 0;
            }
            return right;
        }
    }

    private ListPrograms() {
    }

    /** @return every primitive name */
    public static List<String> primitives() {
        return PRIMITIVES;
    }

    /**
     * Runs one primitive.
     *
     * @param op the primitive
     * @param xs the list
     * @return the result, or {@code null} for an unknown primitive
     */
    public static int[] apply(String op, int[] xs) {
        return switch (op) {
            case "rev" -> {
                int[] o = new int[xs.length];
                for (int i = 0; i < xs.length; i++) {
                    o[i] = xs[xs.length - 1 - i];
                }
                yield o;
            }
            case "sort" -> {
                int[] o = xs.clone();
                Arrays.sort(o);
                yield o;
            }
            case "uniq" -> Arrays.stream(xs).distinct().toArray();
            case "tail" -> xs.length == 0 ? xs : Arrays.copyOfRange(xs, 1, xs.length);
            case "init" -> xs.length == 0 ? xs : Arrays.copyOf(xs, xs.length - 1);
            case "even" -> Arrays.stream(xs).filter(x -> x % 2 == 0).toArray();
            case "odd" -> Arrays.stream(xs).filter(x -> x % 2 != 0).toArray();
            case "dbl" -> {
                int[] o = Arrays.copyOf(xs, 2 * xs.length);
                System.arraycopy(xs, 0, o, xs.length, xs.length);
                yield o.length > 16 ? Arrays.copyOf(o, 16) : o;
            }
            case "head2" -> Arrays.copyOf(xs, Math.min(2, xs.length));
            case "swap" -> {
                int[] o = xs.clone();
                if (o.length >= 2) {
                    int t = o[0];
                    o[0] = o[1];
                    o[1] = t;
                }
                yield o;
            }
            default -> {
                if (op.length() != 2 || "+*".indexOf(op.charAt(0)) < 0) {
                    yield null;
                }
                int[] o = new int[xs.length];
                for (int i = 0; i < xs.length; i++) {
                    o[i] = AbsoluteZero.execute(op, xs[i]);   // the digit DSL, elementwise
                    if (o[i] < 0) {
                        yield null;
                    }
                }
                yield o;
            }
        };
    }

    /**
     * Runs a program.
     *
     * @param program the primitives, in order
     * @param input the input list
     * @return the output, or {@code null} if a primitive is unknown
     */
    public static int[] execute(List<String> program, int[] input) {
        int[] xs = input;
        for (String op : program) {
            xs = apply(op, xs);
            if (xs == null) {
                return null;
            }
        }
        return xs;
    }

    /**
     * Makes a task gluing {@code level} distinct random concepts.
     *
     * @param level how many concepts
     * @param examples how many input/output examples
     * @param random the random source
     * @return the task
     */
    public static Task task(int level, int examples, SplittableRandom random) {
        List<Concept> pool = new ArrayList<>(CONCEPTS);
        List<Concept> chosen = new ArrayList<>();
        for (int i = 0; i < level; i++) {
            chosen.add(pool.remove(random.nextInt(pool.size())));
        }
        return task(chosen, examples, random);
    }

    /**
     * Makes a task from given concepts.
     *
     * @param concepts glued in order
     * @param examples how many examples
     * @param random the random source for the inputs
     * @return the task
     */
    public static Task task(List<Concept> concepts, int examples, SplittableRandom random) {
        List<String> hidden = new ArrayList<>();
        StringBuilder name = new StringBuilder();
        for (Concept c : concepts) {
            hidden.addAll(c.program());
            name.append(name.isEmpty() ? "" : " ").append(c.name());
        }
        int[][] in = new int[examples][];
        int[][] out = new int[examples][];
        for (int e = 0; e < examples; e++) {
            in[e] = new int[5 + random.nextInt(3)];
            for (int i = 0; i < in[e].length; i++) {
                in[e][i] = random.nextInt(10);
            }
            out[e] = execute(hidden, in[e]);
        }
        return new Task(name.toString(), in, out, List.copyOf(hidden), concepts.size());
    }

    /**
     * A curriculum: every concept alone, then pairs and triples of concepts.
     *
     * @param pairs how many two-concept tasks
     * @param triples how many three-concept tasks
     * @param examples examples per task
     * @param seed the seed
     * @return the tasks, easiest first
     */
    public static List<Task> curriculum(int pairs, int triples, int examples, long seed) {
        SplittableRandom random = new SplittableRandom(seed);
        List<Task> out = new ArrayList<>();
        for (Concept c : CONCEPTS) {
            out.add(task(List.of(c), examples, random));
        }
        for (int i = 0; i < pairs; i++) {
            out.add(task(2, examples, random));
        }
        for (int i = 0; i < triples; i++) {
            out.add(task(3, examples, random));
        }
        return out;
    }
}
